#!/usr/bin/env python3
"""Makes src/octant.rs: for each pattern of a 2 x 4 block of pixels the character that draws it (Unicode 16 octants).
Bit i of a pattern is octant i+1:   1 2
                                    3 4
                                    5 6
                                    7 8
230 patterns are the characters BLOCK OCTANT-<numbers>; the other 26 were in Unicode before (blocks, quadrants, quarters), by name below.
Usage: python3 tools/gen_octants.py          (writes src/octant.rs)
       python3 tools/gen_octants.py --check  (is src/octant.rs up to date?)"""
import os
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'src', 'octant.rs')

# the patterns that have no BLOCK OCTANT character: octant numbers -> the name of the character
OTHER = {
    '': 'SPACE',
    '1': 'LEFT HALF UPPER ONE QUARTER BLOCK',
    '2': 'RIGHT HALF UPPER ONE QUARTER BLOCK',
    '12': 'UPPER ONE QUARTER BLOCK',
    '13': 'QUADRANT UPPER LEFT',
    '24': 'QUADRANT UPPER RIGHT',
    '1234': 'UPPER HALF BLOCK',
    '35': 'MIDDLE LEFT ONE QUARTER BLOCK',
    '46': 'MIDDLE RIGHT ONE QUARTER BLOCK',
    '123456': 'UPPER THREE QUARTERS BLOCK',
    '7': 'LEFT HALF LOWER ONE QUARTER BLOCK',
    '57': 'QUADRANT LOWER LEFT',
    '1357': 'LEFT HALF BLOCK',
    '2457': 'QUADRANT UPPER RIGHT AND LOWER LEFT',
    '123457': 'QUADRANT UPPER LEFT AND UPPER RIGHT AND LOWER LEFT',
    '8': 'RIGHT HALF LOWER ONE QUARTER BLOCK',
    '68': 'QUADRANT LOWER RIGHT',
    '1368': 'QUADRANT UPPER LEFT AND LOWER RIGHT',
    '2468': 'RIGHT HALF BLOCK',
    '123468': 'QUADRANT UPPER LEFT AND UPPER RIGHT AND LOWER RIGHT',
    '78': 'LOWER ONE QUARTER BLOCK',
    '5678': 'LOWER HALF BLOCK',
    '135678': 'QUADRANT UPPER LEFT AND LOWER LEFT AND LOWER RIGHT',
    '245678': 'QUADRANT UPPER RIGHT AND LOWER LEFT AND LOWER RIGHT',
    '345678': 'LOWER THREE QUARTERS BLOCK',
    '12345678': 'FULL BLOCK',
}


def bits(numbers):
    return sum(1 << (int(d) - 1) for d in numbers)


def table():
    chars = {}
    for cp in range(0x1CD00, 0x1CE00):
        try:
            name = unicodedata.name(chr(cp))
        except ValueError:
            continue
        if name.startswith('BLOCK OCTANT-'):
            chars[bits(name.split('-')[1])] = chr(cp)
    assert len(chars) == 230, 'this Python has Unicode %s: octants need 16.0' % unicodedata.unidata_version
    for numbers, name in OTHER.items():
        ch = ' ' if name == 'SPACE' else next(chr(cp) for cp in list(range(0x2580, 0x25A0)) + list(range(0x1FB00, 0x1FBF0)) + list(range(0x1CE00, 0x1CEB0))
                                                if unicodedata.name(chr(cp), '') == name)
        assert bits(numbers) not in chars, numbers
        chars[bits(numbers)] = ch
    assert sorted(chars) == list(range(256))
    return [chars[i] for i in range(256)]


def source():
    t = table()
    s = '// Generated by tools/gen_octants.py: do not edit. For each pattern of 2 x 4 pixels (bit i = octant i + 1: 1 2 / 3 4 / 5 6 / 7 8) the character that draws it.\n'
    s += 'pub static OCTANT: [char; 256] = [\n'
    for i in range(0, 256, 8):
        s += '    ' + ' '.join("'%s'," % ('\\u{%x}' % ord(c) if ord(c) > 0x7F else c) for c in t[i:i + 8]) + '\n'
    return s + '];\n'


if __name__ == '__main__':
    src = source()
    if '--check' in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == src
        print('src/octant.rs is up to date' if ok else 'src/octant.rs is OUT OF DATE: run tools/gen_octants.py')
        sys.exit(0 if ok else 1)
    open(OUT, 'w').write(src)
    print('wrote', OUT)
