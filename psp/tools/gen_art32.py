#!/usr/bin/env python3
"""Makes art32.h: the sprites of art.h at 32 x 32 for the PSP screen (the aliens and the explosions are drawn 1:1, no scaling on the screen).
Scale2x doubles a picture and keeps the diagonals smooth; the lower and right edge of a body is then drawn in its dark tone (light comes from the upper left).
The fighter is made 1.5 times as big (every third pixel doubled, a majority vote: 24 x 24, in the middle of its cell), because two fighters of a dual stand 20 pixels apart.
Usage (from psp/): python3 tools/gen_art32.py"""
import re
from collections import Counter

SRC = open('art.h').read()
ART = {m.group(1): re.findall(r'"([^"]*)"', m.group(2)) for m in re.finditer(r'static ArtRows art_(\w+) = \{(.*?)\};', SRC, re.S)}


def full(name):
    return [r + r[::-1] for r in ART[name]]


def scale2x(g):
    h, w = len(g), len(g[0])

    def at(x, y):
        return g[y][x] if 0 <= x < w and 0 <= y < h else '.'
    out = []
    for y in range(h):
        r0 = r1 = ''
        for x in range(w):
            p, a, b, c, d = at(x, y), at(x, y - 1), at(x + 1, y), at(x - 1, y), at(x, y + 1)
            r0 += (a if (c == a and c != d and a != b) else p) + (b if (a == b and a != c and b != d) else p)
            r1 += (c if (d == c and d != b and c != a) else p) + (d if (b == d and b != a and d != c) else p)
        out += [r0, r1]
    return out


def rim(g):
    """The lower and right edge of a body in its dark tone."""
    h, w = len(g), len(g[0])

    def empty(x, y):
        return not (0 <= x < w and 0 <= y < h) or g[y][x] == '.'
    return [''.join('n' if ch in 'mM' and (empty(x, y + 1) or empty(x + 1, y)) else ch for x, ch in enumerate(r)) for y, r in enumerate(g)]


def one_and_a_half(g):
    h, w = len(g), len(g[0])
    big = [[g[y // 3][x // 3] for x in range(w * 3)] for y in range(h * 3)]
    out = []
    for y in range(0, h * 3, 2):
        row = ''
        for x in range(0, w * 3, 2):
            cells = [big[yy][xx] for yy in range(y, min(y + 2, h * 3)) for xx in range(x, min(x + 2, w * 3))]
            row += max(Counter(cells).most_common(), key=lambda t: (t[1], t[0] != '.'))[0]
        out.append(row)
    return out


def centred(rows):
    pad = (32 - len(rows[0])) // 2
    top = (32 - len(rows)) // 2
    rows = ['.' * pad + r + '.' * (32 - pad - len(r)) for r in rows]
    return ['.' * 32] * top + rows + ['.' * 32] * (32 - top - len(rows))


out = ['/* Generated by tools/gen_art32.py: do not edit. 32 x 32 sprites: the letters of art.h (m, M, n: the tones of the variant). */',
       '#ifndef ART32_H', '#define ART32_H', '', '#define ART32 32', 'typedef const char *const ArtRows32[ART32];', '']
for name in ('bee_a', 'bee_b', 'bfly_a', 'bfly_b', 'boss_a', 'boss_b', 'xa0', 'xa1', 'xa2', 'xp0', 'xp1', 'xp2', 'xp3'):
    g = rim(scale2x(full(name)))
    assert len(g) == 32 and all(len(r) == 32 for r in g)
    out.append(f'static ArtRows32 art32_{name} = {{')
    out += ['    "' + r + '",' for r in g]
    out.append('};')
g = centred(one_and_a_half(full('player')))
out.append('static ArtRows32 art32_player = {')
out += ['    "' + r + '",' for r in g]
out.append('};')
out += ['', '#endif', '']
open('art32.h', 'w').write('\n'.join(out))
print('art32.h written')
