#!/usr/bin/env python3
"""Makes art32.h: the sprites of the PSP game at 32 x 32, drawn 1:1 on the screen (no scaling). They are the hand-drawn masters of ../art/master (made by art/master/*.py with
tools/sprites/paint.py; the Amiga versions come from the same scripts): the letters are the letters of the palette in ../amiga/tools/art.py, and the header has the colour of each letter.
The shot (6 x 20) and the bomb (8 x 14, two frames) are hand-drawn rows (art/master/shot.txt, bomb.txt). The fighter is 24 x 30 in the middle of its cell (two fighters of a dual stand 20 pixels apart). The hit boss is the same art in purple.
Usage (from psp/): python3 tools/gen_art32.py"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..', 'tools', 'sprites'))
import master  # noqa: E402

art = master.art
N = 32


def load(name, suffix=''):
    return master.load(name, suffix)[2]


def centred(rows):
    left = (N - len(rows[0])) // 2
    top = (N - len(rows)) // 2
    rows = ['.' * left + r + '.' * (N - left - len(r)) for r in rows]
    return ['.' * N] * top + rows + ['.' * N] * (N - top - len(rows))


cells = {}
for name in ('bee', 'bfly', 'boss'):
    for f, rows in load(name).items():
        cells[f'{name}_{f}'] = rows
purple = {art.TONE['green'][i]: art.TONE['purple'][i] for i in range(7)}
for f, rows in load('boss').items():
    cells[f'bossp_{f}'] = master.recolour(rows, purple)
for i, f in enumerate('abc'):
    cells[f'xa{i}'] = load('xa')[f]
for i, f in enumerate('abcd'):
    cells[f'xp{i}'] = load('xp')[f]
for f, rows in load('bomb').items():
    cells[f'bomb_{f}'] = centred(rows)
cells['shot'] = centred(load('shot')['a'])
cells['player'] = centred(master.recolour(load('ship')['a'], {'w': 'W'}))
for k, rows in cells.items():
    assert len(rows) == N and all(len(r) == N for r in rows), (k, len(rows), len(rows[0]))

letters = sorted({ch for rows in cells.values() for r in rows for ch in r if ch != '.'})
out = ['/* Generated by tools/gen_art32.py: do not edit. 32 x 32 sprites: letters of the palette of amiga/tools/art.py (art32_rgb has the colour of each). */',
       '#ifndef ART32_H', '#define ART32_H', '', '#define ART32 32', 'typedef const char *const ArtRows32[ART32];', '']
out.append('static const unsigned char art32_rgb[128][3] = {')
for code in range(128):
    ch = chr(code)
    r, g, b = art.COLOURS64[art.PEN[ch]] if ch in letters else (0, 0, 0)
    out.append(f'    {{{r}, {g}, {b}}},' + (f'   /* {ch} */' if ch in letters else ''))
out.append('};')
out.append('')
for k, rows in cells.items():
    out.append(f'static ArtRows32 art32_{k} = {{')
    out += ['    "' + r + '",' for r in rows]
    out.append('};')
out += ['', '#endif', '']
open(os.path.join(HERE, '..', 'art32.h'), 'w').write('\n'.join(out))
print('art32.h written:', len(cells), 'sprites')
